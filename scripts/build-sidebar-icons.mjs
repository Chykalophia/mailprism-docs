#!/usr/bin/env node
/**
 * Writes src/css/sidebar-icons.css from src/components/Icon/icons.json, so the
 * sidebar category icons and the React <Icon> share one set. Each sidebar
 * category in sidebars.ts carries className "cat-<icon>". Run after editing
 * icons.json: node scripts/build-sidebar-icons.mjs
 */
import {readFileSync, writeFileSync} from 'node:fs';

const icons = JSON.parse(readFileSync(new URL('../src/components/Icon/icons.json', import.meta.url)));
const used = ['rocket', 'inbox', 'zap', 'sparkles', 'reply', 'users', 'chart', 'file', 'plug', 'bell', 'sliders', 'lifebuoy'];

const missing = used.filter((n) => !(n in icons));
if (missing.length) throw new Error(`Unknown icon(s) in build-sidebar-icons.mjs: ${missing.join(', ')}`);

const uri = (name) =>
  `url("data:image/svg+xml,${encodeURIComponent(
    `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='1.9' stroke-linecap='round' stroke-linejoin='round'>${icons[name]}</svg>`,
  )}")`;

let css = '/* Generated by scripts/build-sidebar-icons.mjs. Do not edit by hand. */\n';
for (const name of used) {
  css += `.cat-${name} > .menu__list-item-collapsible > .menu__link::before { -webkit-mask-image: ${uri(name)}; mask-image: ${uri(name)}; }\n`;
}
writeFileSync(new URL('../src/css/sidebar-icons.css', import.meta.url), css);
console.log(`wrote ${used.length} sidebar icons`);
