import React from 'react';
import useBaseUrl from '@docusaurus/useBaseUrl';
import ThemedImage from '@theme/ThemedImage';
import styles from './styles.module.css';

type Props = {
  /** Path under static/, e.g. "/img/screens/inbox/overview.png". */
  src: string;
  /** Optional dark-mode variant, shown when the docs are in dark mode. */
  srcDark?: string;
  /** Describes what the screenshot shows, for screen readers. Required. */
  alt: string;
  /** Short visible caption under the image. */
  caption?: React.ReactNode;
  /** Max display width in px (emails and dialogs read better narrower). */
  width?: number;
};

/**
 * A screenshot from the MailPrism app, framed to match the docs.
 * Images are generated by scripts/screenshots (fake demo data only).
 */
export default function Screenshot({src, srcDark, alt, caption, width}: Props) {
  const light = useBaseUrl(src);
  const dark = useBaseUrl(srcDark ?? src);
  return (
    <figure className={styles.figure} style={width ? {maxWidth: width} : undefined}>
      <a href={light} target="_blank" rel="noopener" className={styles.link} aria-label={`Open full-size screenshot: ${alt}`}>
        <ThemedImage className={styles.img} alt={alt} sources={{light, dark}} loading="lazy" decoding="async" />
      </a>
      {caption && <figcaption className={styles.caption}>{caption}</figcaption>}
    </figure>
  );
}
